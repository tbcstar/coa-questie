"""Turn the server's own quest titles into the client's quest-name table.

Questie's database names are English. The CoA server keeps its Chinese in
quest_template.LogTitle, which the client repeats for quests that are in the
log, but a quest that is not (a map pin, a journey entry, a chat link) falls
back to the English database. This script reads every quest_template write in
the server's SQL (the base dump and both update folders, which is where the
CoA-only quests live) and writes the titles to
Questie-X/Localization/QuestNames.lua.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SERVER = os.path.join(os.path.dirname(REPO), 'azerothcore-wotlk-coa', 'data', 'sql')
DEFAULT_SOURCES = [
    os.path.join(SERVER, 'base', 'db_world', 'quest_template.sql'),
    os.path.join(SERVER, 'updates', 'pending_db_world'),
    os.path.join(SERVER, 'updates', 'db_world'),
]
OUT = os.path.join(REPO, 'Questie-X', 'Localization', 'QuestNames.lua')

CJK = re.compile('[\u3400-\u9fff\uf900-\ufaff]')
INSERT = re.compile(r'INSERT INTO\s+`?quest_template`?\s*(?:\(([^)]*)\))?\s*VALUES')


def table_columns(text, table):
    start = text.index('CREATE TABLE `%s`' % table)
    end = text.index(') ENGINE', start)
    return re.findall(r'^\s+`([^`]+)`\s', text[start:end], re.M)


def parse_values(text, start):
    i, n = start, len(text)
    while i < n:
        while i < n and text[i] in ' \t\r\n,':
            i += 1
        if i >= n or text[i] != '(':
            return i
        i += 1
        row, cell, quoted = [], None, False
        while i < n:
            c = text[i]
            if quoted:
                if c == '\\':
                    cell = (cell or '') + text[i + 1]
                    i += 2
                    continue
                if c == "'":
                    quoted = False
                else:
                    cell = (cell or '') + c
            elif c == "'":
                quoted = True
                cell = '' if cell is None else cell
            elif c == ',':
                row.append(cell)
                cell = None
            elif c == ')':
                row.append(cell)
                i += 1
                yield row
                break
            else:
                cell = (cell or '') + c
            i += 1
        if i >= n:
            return i
        if text[i] == ';':
            return i + 1


def sql_files(sources):
    for source in sources:
        if os.path.isdir(source):
            for name in sorted(os.listdir(source)):
                if name.lower().endswith('.sql'):
                    yield os.path.join(source, name)
        elif os.path.isfile(source):
            yield source


def read_titles(sources):
    titles, rows, files = {}, 0, 0
    for path in sql_files(sources):
        text = open(path, encoding='utf-8', errors='replace').read()
        if 'quest_template' not in text:
            continue
        if 'CREATE TABLE' in text and '`quest_template` (' in text:
            try:
                default_columns = table_columns(text, 'quest_template')
            except ValueError:
                default_columns = None
        else:
            default_columns = None
        used = False
        for match in INSERT.finditer(text):
            columns = default_columns
            if match.group(1):
                columns = [c.strip().strip('`') for c in match.group(1).split(',')]
            if not columns or 'ID' not in columns or 'LogTitle' not in columns:
                continue
            id_at, log_at = columns.index('ID'), columns.index('LogTitle')
            for row in parse_values(text, match.end()):
                rows += 1
                try:
                    quest_id = int(str(row[id_at]).strip())
                except (IndexError, TypeError, ValueError):
                    continue
                title = row[log_at] if log_at < len(row) else None
                if title and CJK.search(title):
                    titles[quest_id] = title.strip()
                    used = True
        if used:
            files += 1
    return titles, rows, files


def lua_quote(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_lua(titles, out_path, newline):
    lines = [
        '--- The names the server itself gives its quests.',
        "-- Questie's database names are English. A CoA client reports enUS while its",
        '-- quest log is Chinese, and a quest that is not in the log yet (a map pin,',
        '-- a journey entry, a chat link) was listed in English (21 Nov 2026). These',
        '-- are the titles from quest_template.LogTitle, generated by',
        '-- tools/coadb/gen_questnames.py; do not hand-edit.',
        'QuestieQuestNames = {',
    ]
    for quest_id in sorted(titles):
        lines.append('    [%d] = %s,' % (quest_id, lua_quote(titles[quest_id])))
    lines.append('}')
    lines.append('')
    with open(out_path, 'w', encoding='utf-8', newline='') as handle:
        handle.write(newline.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', action='append', default=None,
                        help='SQL file or folder to read (repeatable; default: the server\'s SQL)')
    parser.add_argument('--out', default=OUT, help='QuestNames.lua to write')
    parser.add_argument('--dry-run', action='store_true', help='only report counts')
    args = parser.parse_args()
    sources = args.source or DEFAULT_SOURCES
    missing = [s for s in sources if not os.path.exists(s)]
    if missing:
        sys.exit('missing: %s' % ', '.join(missing))
    titles, rows, files = read_titles(sources)
    print('files %d, rows %d, titles %d' % (files, rows, len(titles)))
    if args.dry_run:
        sample = {str(k): titles[k] for k in sorted(titles)[:5]}
        print(json.dumps(sample, ensure_ascii=True))
        return
    probe = OUT if os.path.isfile(OUT) else os.path.join(REPO, 'Questie-X', 'Localization', 'l10n.lua')
    newline = '\r\n' if open(probe, 'rb').read(400).count(b'\r\n') else '\n'
    write_lua(titles, args.out, newline)
    print('wrote %s (%d bytes)' % (args.out, os.path.getsize(args.out)))


if __name__ == '__main__':
    main()
