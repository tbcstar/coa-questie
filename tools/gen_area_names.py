#!/usr/bin/env python3
r"""Generate Questie-X/Localization/Translations/Zones/CoAZoneNames.lua.

Questie's zone translations only name the big zones ("Tirisfal Glades"); the
sub-areas a tracker header actually shows ("Deathknell", "Brill", ...) have no
zhCN entry, so the header stayed English on a Chinese client. The client's own
AreaTable.dbc already holds the Chinese name for every one of them, and
social_diary's port generated that table (Locales/zhCN/Areas.lua) from it.

This script copies those pairs into a Questie translation file. It only fills
an entry whose zhCN is missing or false, so hand-written translations keep
winning.

    py -3 -B tools\gen_area_names.py [--areas <Areas.lua>] [--dry-run]
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'Questie-X', 'Localization', 'Translations', 'Zones', 'CoAZoneNames.lua')
DEFAULT_AREAS = os.path.join('D:', os.sep, 'DSH-source', 'social_diary', 'Locales', 'zhCN', 'Areas.lua')

PAIR = re.compile(r'^\s*\["((?:[^"\\]|\\.)*)"\]\s*=\s*"((?:[^"\\]|\\.)*)",\s*$')


def unescape(text):
    return text.replace('\\"', '"').replace('\\\\', '\\')


def read_areas(path):
    with open(path, encoding='utf-8') as handle:
        text = handle.read()
    start = text.find('local generated = {')
    if start < 0:
        raise SystemExit('no generated table in ' + path)
    pairs = {}
    for line in text[start:].splitlines():
        match = PAIR.match(line)
        if not match:
            continue
        english = unescape(match.group(1))
        chinese = unescape(match.group(2))
        if not english or not chinese or '\\' in chinese:
            continue
        if not re.search(r'[\u4e00-\u9fff]', chinese):
            continue
        pairs[english] = chinese
    return pairs


def lua_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--areas', default=DEFAULT_AREAS)
    parser.add_argument('--dry-run', action='store_true')
    options = parser.parse_args()

    pairs = read_areas(options.areas)
    names = sorted(pairs.items())
    lines = []
    add = lines.append
    add('-- Area names the client itself knows, in Chinese.')
    add('--')
    add('-- Questie names the big zones only (Translations\\Zones\\*.lua). The sub-areas a')
    add('-- tracker header shows - "Deathknell", "Brill", "The Bulwark" - had no zhCN')
    add('-- entry, so a Chinese client read them in English. The client AreaTable.dbc has')
    add('-- all of them; generated by tools\\gen_area_names.py from the DBC table')
    add('-- social_diary\'s port extracted (Locales\\zhCN\\Areas.lua). Do not hand-edit:')
    add('-- add a correction to the generator or to a Translations file instead.')
    add('---@type l10n')
    add('local l10n = QuestieLoader:ImportModule("l10n")')
    add('')
    add('local areaNames = {')
    for english, chinese in names:
        add('    [' + lua_string(english) + '] = ' + lua_string(chinese) + ',')
    add('}')
    add('')
    add('-- Fill only what no translation file named yet, so curated names keep winning.')
    add('for english, chinese in pairs(areaNames) do')
    add('    local entry = l10n.translations[english]')
    add('    if not entry then')
    add('        entry = {}')
    add('        l10n.translations[english] = entry')
    add('    end')
    add('    if entry["zhCN"] == nil or entry["zhCN"] == false then')
    add('        entry["zhCN"] = chinese')
    add('    end')
    add('end')
    add('')

    body = '\n'.join(lines)
    print('pairs', len(names), 'bytes', len(body.encode('utf-8')))
    if options.dry_run:
        print(body[:400])
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(body)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
